/**
 * The pure half of `scripts/patch-library-index.mjs` (#561): which files in
 * a bank folder (`packages/engine/src/patches/`, and since windsor#877
 * `packages/engine/src/racks/`) are library files, and the text of the
 * `index.ts` that imports every one of them statically. Static imports are the
 * one mechanism Vite (the game), esbuild (the standalone editor) and Vitest
 * share — `import.meta.glob` is Vite-only — so the index is generated and
 * `npm run verify` refuses a stale one, the way `client-dir-table.mjs` does.
 */
// reads-by-path: none (reads the folder its caller passes)
import { readdirSync } from 'node:fs';

/** A filename slug — the same rule `patchLibrary.ts` enforces on load. */
export const PATCH_ID_RULE = /^[a-z0-9]+(-[a-z0-9]+)*$/;

/**
 * The two banks, each a folder under `packages/engine/src` with a generated
 * `index.ts`: its exported constant, the identifier prefix of each import,
 * what one file is, and the module that validates the map.
 */
export const BANKS = [
  { dir: 'patches', constant: 'PATCH_FILES', prefix: 'patch', what: 'patch', loader: 'presets.ts' },
  {
    dir: 'racks',
    constant: 'RACK_FILES',
    prefix: 'rack',
    what: 'rack',
    loader: 'rack/rackBank.ts',
  },
];

/** The ids of every `<id>.json` in `dir`, sorted; throws on a file that is not a slug. */
export function patchIdsIn(dir) {
  const ids = [];
  for (const name of readdirSync(dir).sort()) {
    if (name === 'index.ts') continue;
    if (!name.endsWith('.json'))
      throw new Error(`${dir}/${name}: only <id>.json files belong here`);
    const id = name.slice(0, -'.json'.length);
    if (!PATCH_ID_RULE.test(id))
      throw new Error(`${dir}/${name}: "${id}" is not a slug (lower-case words joined by hyphens)`);
    ids.push(id);
  }
  return ids;
}

/**
 * `score-drowned-cellos` → `patch_score_drowned_cellos`. The prefix keeps a
 * slug like `new` or `1st` legal, and hyphen → underscore is injective over
 * slugs (a slug has no underscore), so `a1` and `a-1` never share a binding.
 */
export const identifierFor = (id, prefix = 'patch') => `${prefix}_${id.replaceAll('-', '_')}`;

/** Prettier's quoteProps is "as-needed": only a plain identifier goes unquoted. */
const UNQUOTED_KEY = /^[a-z][a-z0-9]*$/;

/** The generated module: one default import per file, one map keyed by id. */
export function renderIndex(ids, bank = BANKS[0]) {
  const lines = [
    '// Generated by scripts/patch-library-index.mjs from the files beside it — do not edit.',
    '// `node scripts/patch-library-index.mjs --write` regenerates it; `npm run verify` checks it.',
    `// One static import per ${bank.what} is what Vite, esbuild and Vitest all bundle (#561).`,
  ];
  for (const id of ids) lines.push(`import ${identifierFor(id, bank.prefix)} from './${id}.json';`);
  lines.push(
    '',
    `/** Every library file, raw and unvalidated, keyed by id (\`${bank.loader}\` loads it). */`,
  );
  const head = `export const ${bank.constant}: Readonly<Record<string, unknown>> = {`;
  // An empty bank is one line, as Prettier would print it.
  if (ids.length === 0) lines.push(`${head}};`, '');
  else {
    lines.push(head);
    for (const id of ids)
      lines.push(`  ${UNQUOTED_KEY.test(id) ? id : `'${id}'`}: ${identifierFor(id, bank.prefix)},`);
    lines.push('};', '');
  }
  return lines.join('\n');
}
